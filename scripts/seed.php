<?php
declare(strict_types=1);

// Тестовые данные для показа: 10 демо-пользователей (demo01 … demo10) и 50 их материалов
// случайных типов, у каждого один файл .md. Запускать можно повторно: прежние демо-аккаунты
// и их материалы удаляются, обычные аккаунты не затрагиваются.
// Запуск (панель и модуль MySQL-8.4 включены): php scripts/seed.php
// Только удалить демо-данные, ничего не создавая: php scripts/seed.php clear
if (PHP_SAPI !== 'cli') {
    exit;
}

require __DIR__ . '/../backend/bootstrap.php';

// Пароль всех демо-аккаунтов. Только для разработки.
const DEMO_PASSWORD = 'demo12345';

// Имена первых восьми пользователей; у остальных имени нет, и они видны как «User…».
const NAMES = [['Анна', 'Кузнецова'], ['Михаил', 'Соколов'], ['Дарья', 'Морозова'], ['Илья', 'Павлов'],
    ['Елена', 'Титова'], ['Максим', 'Орлов'], ['Алина', 'Беляева'], ['Денис', 'Романов']];

const TOPICS = [
    'Математика' => ['Линейная алгебра', 'Математический анализ', 'Дискретная математика', 'Теория вероятностей', 'Дифференциальные уравнения', 'Аналитическая геометрия'],
    'Информатика' => ['Алгоритмы и структуры данных', 'Базы данных и SQL', 'Компьютерные сети', 'Операционные системы', 'Веб-разработка', 'Python для начинающих'],
    'Физика' => ['Механика', 'Электричество и магнетизм', 'Термодинамика', 'Оптика', 'Квантовая физика', 'Физика колебаний'],
    'Экономика' => ['Микроэкономика', 'Макроэкономика', 'Финансы и кредит', 'Бухгалтерский учёт', 'Маркетинг', 'Статистика'],
    'Право' => ['Теория государства и права', 'Конституционное право', 'Гражданское право', 'Уголовное право', 'Трудовое право', 'Римское право'],
    'Английский язык' => ['Грамматика B1–B2', 'Деловая лексика', 'Времена глаголов', 'Подготовка к IELTS', 'Фразовые глаголы', 'Академическое письмо'],
    'История' => ['История России XIX века', 'Древний мир', 'Средние века', 'Новейшая история', 'Историография', 'Культура и общество'],
    'Химия' => ['Органическая химия', 'Неорганическая химия', 'Физическая химия', 'Аналитическая химия', 'Биохимия', 'Химическая кинетика'],
];

// Тип => [окончание названия, описание].
const KINDS = [
    'notes' => ['конспект лекций', 'Главное из лекций в коротких пунктах: определения, примеры и схемы.'],
    'solutions' => ['задачи с решениями', 'Разобранные задачи с пошаговыми решениями и ответами.'],
    'cheatsheet' => ['шпаргалка', 'Формулы и определения на нескольких страницах, только то, что спрашивают.'],
];

const PRICES = [0, 0, 0, 30, 40, 50, 60, 80, 90, 120, 150, 180];

$db = db();
$auth = new AuthHandler($db);
$market = new Market($db);

foreach ($db->query("SELECT id FROM users WHERE login REGEXP '^demo[0-9]{2}$'")->fetchAll(PDO::FETCH_COLUMN) as $id) {
    $auth->delete((int) $id);
}
if (($argv[1] ?? '') === 'clear') {
    exit("Демо-пользователи и их материалы удалены.\n");
}

$users = [];
for ($i = 0; $i < 10; $i++) {
    [$first, $last] = NAMES[$i] ?? [null, null];
    $users[] = $auth->register(sprintf('demo%02d', $i + 1), DEMO_PASSWORD, [
        'first_name' => $first, 'last_name' => $last, 'email' => null, 'course' => random_int(1, 4),
    ]);
}

// 48 тем (8 предметов по 6) и ещё 2 повтора с другим типом: по 5 материалов на пользователя.
$topics = [];
foreach (TOPICS as $subject => $list) {
    foreach ($list as $topic) {
        $topics[] = [$subject, $topic];
    }
}
$topics = [...$topics, ...array_map(fn() => $topics[array_rand($topics)], [1, 2])];
shuffle($topics);

foreach ($topics as $i => [$subject, $topic]) {
    $type = array_rand(KINDS);
    [$suffix, $description] = KINDS[$type];
    $title = "$topic: $suffix";

    // Файл .md создаётся во временной папке, сохранение переносит его в хранилище.
    $tmp = tempnam(sys_get_temp_dir(), 'seed');
    $text = "# $title\n\nПредмет: $subject.\n\n$description\n";
    file_put_contents($tmp, $text);
    $file = ['name' => "$topic.md", 'tmp' => $tmp, 'size' => strlen($text), 'mime' => 'text/markdown'];

    $id = $market->create($users[$i % 10], [$title, $description, $subject, $type, random_int(1, 4), PRICES[array_rand(PRICES)]], [$file]);
    // Даты публикации раскидываем по последним 30 дням.
    $db->prepare('UPDATE materials SET created_at = NOW() - INTERVAL ? MINUTE WHERE id = ?')->execute([random_int(60, 30 * 24 * 60), $id]);
}

echo "Готово: 10 пользователей, 50 материалов. Логины demo01 … demo10, пароль — константа DEMO_PASSWORD в этом файле.\n";
